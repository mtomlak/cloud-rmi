#ifndef CLOUDRMI_VERSION_H
#define CLOUDRMI_VERSION_H

#define CLOUDRMI_PROTOCOL_VERSION 2
#define CLOUDRMI_PROTOCOL_VERSION_STRING "2"

#define CLOUDRMI_LIBRARY_VERSION_MAJOR 2
#define CLOUDRMI_LIBRARY_VERSION_MINOR 1
#define CLOUDRMI_LIBRARY_VERSION_PATCH 0
#define CLOUDRMI_LIBRARY_VERSION "2.1.0"

#if CLOUDRMI_LIBRARY_VERSION_MAJOR != CLOUDRMI_PROTOCOL_VERSION
#error "Library major version must match protocol version"
#endif

#define RMI_MAX_PROTOCOL_VERSION CLOUDRMI_PROTOCOL_VERSION
#define RMI_BUF_SZ 8192
#define RMI_MAX_LINE RMI_BUF_SZ

#ifndef RMI_MAX_PAYLOAD
#define RMI_MAX_PAYLOAD (10 * 1024 * 1024)
#endif

#ifndef RMI_DEFAULT_MAX_PAYLOAD
#define RMI_DEFAULT_MAX_PAYLOAD RMI_MAX_PAYLOAD
#endif
#ifndef RMI_MAX_BUFFER
#define RMI_MAX_BUFFER RMI_MAX_PAYLOAD
#endif

#ifndef RMI_PAYLOAD_PREALLOC_ENABLED
#define RMI_PAYLOAD_PREALLOC_ENABLED 1
#endif

#ifndef RMI_PAYLOAD_PREALLOC
#define RMI_PAYLOAD_PREALLOC (128 * 1024)
#endif

#ifndef RMI_INLINE_PAYLOAD_THRESHOLD
#define RMI_INLINE_PAYLOAD_THRESHOLD (RMI_MAX_LINE - ((RMI_MAX_LINE * 35) / 100) - 500)
#endif

#endif /* CLOUDRMI_VERSION_H */
